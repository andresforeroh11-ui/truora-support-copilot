-- 09 · Número de caso, hora de inicio de incidentes y consulta por caso
-- - tickets.numero_caso: número legible (#1001, #1002...) en orden de llegada
-- - incidentes.casos / inicio_at: casos involucrados y desde cuándo ocurre
-- - v_clasificaciones_vivas: expone numero_caso y hora de llegada del ticket
-- - v_caso_detalle: una fila por caso para que el bot (P5) responda preguntas
-- - v_resumen_diario: agrega número de caso y hora "desde" a SLA, incidentes y patrones
-- =====================================================================

alter table tickets add column if not exists numero_caso bigint;
update tickets t set numero_caso = s.n
from (select id, 1000 + row_number() over (order by created_at, id) as n from tickets) s
where s.id = t.id;
alter table tickets alter column numero_caso set not null;
alter table tickets alter column numero_caso add generated by default as identity;
select setval(pg_get_serial_sequence('tickets', 'numero_caso'), (select max(numero_caso) from tickets));
alter table tickets add constraint tickets_numero_caso_key unique (numero_caso);

alter table incidentes add column if not exists casos bigint[];
alter table incidentes add column if not exists inicio_at timestamptz;

create or replace view v_clasificaciones_vivas with (security_invoker = true) as
select c.id, c.created_at, c.ticket_id, c.modelo, c.prompt_version, c.producto, c.pais, c.ambiente, c.tipo,
       c.origen_falla, c.codigo_motivo, c.severidad, c.confianza, c.justificacion, c.datos_faltantes,
       c.requiere_escalamiento, c.accion_sugerida, c.json_crudo, c.json_valido, c.error, c.latencia_ms,
       c.tokens_entrada, c.tokens_salida, c.costo_usd,
       t.numero_caso, t.created_at as ticket_created_at
from clasificaciones c
join tickets t on t.id = c.ticket_id
where not t.es_set_prueba;

create or replace view v_caso_detalle with (security_invoker = true) as
select t.numero_caso, t.ticket_ref, t.created_at as recibido_at, t.cliente, t.pais, t.canal, t.asunto, t.cuerpo,
       c.severidad, c.origen_falla, c.producto, c.ambiente, c.codigo_motivo, c.accion_sugerida,
       c.requiere_escalamiento, c.justificacion, c.datos_faltantes, c.confianza, c.created_at as clasificado_at,
       r.tipo as respuesta_tipo, r.estado as respuesta_estado, r.borrador, r.texto_final, r.revisado_at,
       e.estado as escalamiento_estado, e.hipotesis, e.ficha, e.created_at as escalado_at,
       i.incidente
from tickets t
left join lateral (select * from clasificaciones x where x.ticket_id = t.id order by x.created_at desc limit 1) c on true
left join lateral (select * from respuestas x where x.ticket_id = t.id order by x.created_at desc limit 1) r on true
left join lateral (select * from escalamientos x where x.ticket_id = t.id order by x.created_at desc limit 1) e on true
left join lateral (
  select jsonb_build_object('firma', x.firma, 'estado', x.estado, 'detectado_at', x.created_at,
                            'inicio_at', x.inicio_at, 'casos', x.casos, 'codigo_motivo', x.codigo_motivo) as incidente
  from incidentes x where t.id = any (x.ticket_ids) order by x.created_at desc limit 1) i on true;

